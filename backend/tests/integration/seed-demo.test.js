let repl, dir;
let uploads = 0;
const media = mediaService({ name: 'test', upload: async () => ({ storageKey: 'demo-' + ++uploads, resourceType: 'image', format: 'png', deliveryType: 'authenticated' }), access: async () => 'https://example.test/private-demo.png', remove: async () => {} });
const config = { BOOKING_RESERVATION_MINUTES: 15, COMMISSION_BASIS_POINTS: 1000, JWT_ACCESS_SECRET: 'a'.repeat(40), JWT_REFRESH_SECRET: 'b'.repeat(40), JWT_ACCESS_EXPIRES_IN: '15m', JWT_REFRESH_EXPIRES_IN: '7d' };
beforeAll(async () => {
  repl = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  await connectDatabase(repl.getUri()); await ensureIndexes();
  dir = await mkdtemp(join(tmpdir(), 'skilllink-demo-'));
});
afterAll(async () => { await disconnectDatabase(); await repl?.stop(); if (dir) await rm(dir, { recursive: true, force: true }); });
it('seeds every stage, preserves ledger and user progress on rerun, adds photos later and supports real lifecycle operations', async () => {
  const options = { config, media, localDir: join(dir, 'local'), assetsDir: join(dir, 'assets'), cleanup: true };
  await seedDemo(options);
  expect(await User.countDocuments()).toBe(14);
  expect(await WorkerProfile.countDocuments()).toBe(10);
  expect(await Verification.countDocuments({ status: 'PENDING' })).toBe(1);
  expect(await FinancialLedgerEntry.countDocuments()).toBe(16);
  expect((await Booking.find()).map(b => b.status).sort()).toEqual([...demoStages].sort());
  const logins = JSON.parse(await readFile(join(options.localDir, 'demo-logins.json'), 'utf8'));
  const auth = authService(config);
  for (const account of logins.accounts) expect((await auth.login(account)).user.role).toBe(account.role);
  const discovery = await discoveryService(media).search({ page: 1, limit: 20, sort: 'trust' });
  expect(discovery.pagination.total).toBe(10);
  expect(new Set(discovery.workers.flatMap(w => w.services.map(s => s.name))).size).toBe(8);
  for (const w of discovery.workers) expect(w.professionTitle.length).toBeGreaterThan(8);
  const carpenter = await WorkerProfile.findOne({ user: demoId('user:ebou-ceesay') });
  expect((await Service.findById(carpenter.services[0])).name).toBe('Carpentry');
  await matchingService().eligibleProfile(String(carpenter.user));
  await expect(matchingService().eligibleProfile(String(demoId('user:isatou-jatta')))).rejects.toMatchObject({ code: 'WORKER_INELIGIBLE' });
  // A normal worker action advances the fixture. The seed must not rewind it.
  const lifecycle = lifecycleService(media);
  const confirmed = await Booking.findById(demoId('booking:CONFIRMED'));
  const worker = await User.findById(confirmed.worker);
  await lifecycle.start(confirmed.id, worker);
  const ledgerBefore = JSON.stringify(await FinancialLedgerEntry.find().sort({ _id: 1 }).lean());
  const customer = await User.findById(confirmed.customer);
  await User.updateOne({ _id: customer._id }, { $set: { firstName: 'Edited in app' } });
  const photoDir = join(options.assetsDir, 'ebou-ceesay'); await mkdir(photoDir, { recursive: true });
  await writeFile(join(photoDir, 'profile.png'), await sharp({ create: { width: 32, height: 32, channels: 3, background: '#995522' } }).png().toBuffer());
  await seedDemo(options);
  expect(await User.countDocuments()).toBe(14);
  expect(await Booking.countDocuments()).toBe(7);
  expect((await Booking.findById(confirmed._id)).status).toBe('IN_PROGRESS');
  expect((await User.findById(customer._id)).firstName).toBe('Edited in app');
  expect(JSON.stringify(await FinancialLedgerEntry.find().sort({ _id: 1 }).lean())).toBe(ledgerBefore);
  expect((await WorkerProfile.findById(carpenter._id)).profileImage).toBeTruthy();
  const uploaded = uploads; await seedDemo(options); expect(uploads).toBe(uploaded);
  expect(JSON.parse(await readFile(join(options.localDir, 'demo-logins.json'), 'utf8')).accounts).toEqual(logins.accounts);
  expect(await Payment.countDocuments()).toBe(5);
  const unpaid = await Booking.findById(demoId('booking:AWAITING_PAYMENT'));
  await paymentService(config, new MockPaymentProvider()).checkout(unpaid.id, await User.findById(unpaid.customer), { idempotencyKey: 'seed-test-payment', outcome: 'SUCCESS' });
  expect((await Booking.findById(unpaid._id)).status).toBe('CONFIRMED');
  const marked = await Booking.findById(demoId('booking:WORKER_MARKED_COMPLETED'));
  const owner = await User.findById(marked.customer);
  await lifecycle.confirm(marked.id, owner);
  await lifecycle.review(marked.id, owner, { rating: 5, comment: 'The work was finished carefully.' });
  expect((await Payment.findOne({ booking: marked._id })).status).toBe('RELEASED');
}, 120000);

it('archives only identified Integration accounts and repairs the known carpenter label without altering financial history', async () => {
  const electrical = await Service.findOne({ name: 'Electrician' });
  const carpenter = await Service.findOne({ name: 'Carpentry' });
  const oldCustomer = await User.create({ _id: '6add87261c357b3bb8d632b2', firstName: 'Integration', lastName: 'Customer', role: 'CUSTOMER', email: 'old-customer@example.test', phoneNumber: '+999777777771', password: 'Test-password123' });
  const oldWorker = await User.create({ _id: '6add872c1c357b3bb8d632d6', firstName: 'Integration', lastName: 'Worker', role: 'WORKER', email: 'old-worker@example.test', phoneNumber: '+999777777772', password: 'Test-password123' });
  const realCustomer = await User.findById(demoId('user:amadou-gaye'));
  const pure = await Conversation.create({ contextType: 'DIRECT_PROPOSAL', contextId: new mongoose.Types.ObjectId(), customer: oldCustomer._id, worker: oldWorker._id, participants: [oldCustomer._id, oldWorker._id] });
  const mixed = await Conversation.create({ contextType: 'DIRECT_PROPOSAL', contextId: new mongoose.Types.ObjectId(), customer: realCustomer._id, worker: oldWorker._id, participants: [realCustomer._id, oldWorker._id] });
  for (const c of [pure, mixed]) await Message.create({ conversation: c._id, sender: c.customer, type: 'TEXT', text: 'Retain mixed real chat', clientMessageId: c.id });
  const oldBooking = await Booking.create({ customer: oldCustomer._id, worker: oldWorker._id, service: electrical._id, description: 'Old demo', agreedAmountBututs: 50000, scheduledStart: new Date(), scheduledEnd: new Date(Date.now() + 3600000), status: 'COMPLETED' });
  const oldPayment = await Payment.create({ booking: oldBooking._id, customer: oldCustomer._id, worker: oldWorker._id, amountBututs: 50000, platformFeeBututs: 5000, workerAmountBututs: 45000, commissionBasisPoints: 1000, provider: 'mock', status: 'RELEASED' });
  await FinancialLedgerEntry.create({ booking: oldBooking._id, payment: oldPayment._id, customer: oldCustomer._id, worker: oldWorker._id, type: 'WORKER_RELEASE', amountBututs: 45000 });
  const musa = await User.create({ _id: '6adea1f1c3fcd71ca2c07e82', firstName: 'Musa', lastName: 'Banja', role: 'WORKER', email: 'musa@example.test', phoneNumber: '+999777777773', password: 'Test-password123' });
  const offer = await DirectProposal.create({ _id: '6adfc8276ca734c3bf3dbba6', customer: realCustomer._id, worker: musa._id, service: electrical._id, description: 'Repair wood', scheduledStart: new Date(), scheduledEnd: new Date(Date.now() + 3600000), expiresAt: new Date(), agreedAmountBututs: 50000, status: 'ACCEPTED' });
  const booking = await Booking.create({ customer: realCustomer._id, worker: musa._id, service: electrical._id, directProposal: offer._id, description: offer.description, scheduledStart: offer.scheduledStart, scheduledEnd: offer.scheduledEnd, agreedAmountBututs: 50000, status: 'COMPLETED' });
  offer.booking = booking._id; await offer.save();
  const ledgerBefore = JSON.stringify(await FinancialLedgerEntry.find().sort({ _id: 1 }).lean());
  const options = { config, media, localDir: join(dir, 'local'), assetsDir: join(dir, 'assets') };
  await seedDemo(options); await seedDemo(options);
  expect((await User.findById(oldCustomer._id)).accountStatus).toBe('DISABLED');
  expect((await User.findById(musa._id)).accountStatus).toBe('ACTIVE');
  expect((await Booking.findById(oldBooking._id)).adminArchivedAt).toBeTruthy();
  expect(await Message.countDocuments({ conversation: pure._id })).toBe(0);
  expect(await Message.countDocuments({ conversation: mixed._id })).toBe(1);
  const repaired = await Booking.findById(booking._id);
  expect(String(repaired.service)).toBe(carpenter.id);
  expect(repaired.agreedAmountBututs).toBe(50000);
  expect(repaired.status).toBe('COMPLETED');
  expect(repaired.adminArchivedAt).toBeUndefined();
  expect(JSON.stringify(await FinancialLedgerEntry.find().sort({ _id: 1 }).lean())).toBe(ledgerBefore);
}, 120000);
