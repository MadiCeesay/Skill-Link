import { test, expect } from '@playwright/test';
const api = 'http://127.0.0.1:5001/api';
async function auth(request, email) {
  const r = await request.post(api + '/auth/login', { data: { email, password: 'Test-password123' } });
  expect(r.ok()).toBe(true); return (await r.json()).data;
}
async function login(page, email) {
  await page.goto('/login'); await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Test-password123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click(); await expect(page).not.toHaveURL(/\/login$/);
}
test('job and proposal maps save GeoJSON pins and protect exact worker locations until payment', async ({ browser, request }) => {
  test.setTimeout(240000);
  const customer = await auth(request, 'customer@example.test'), worker = await auth(request, 'professional@example.test');
  const ch = { Authorization: 'Bearer ' + customer.accessToken }, wh = { Authorization: 'Bearer ' + worker.accessToken };
  const profile = (await (await request.get(api + '/workers/' + worker.user.id)).json()).data.worker;
  const service = profile.services.find(s => s.name === 'Electrician');
  const cc = await browser.newContext({ viewport: { width: 1440, height: 950 }, geolocation: { longitude: -16.65, latitude: 13.27 }, permissions: ['geolocation'] });
  await cc.addInitScript(() => {
    window.locationRequests = 0;
    const locate = navigator.geolocation.getCurrentPosition.bind(navigator.geolocation);
    navigator.geolocation.getCurrentPosition = (...args) => { window.locationRequests++; locate(...args); };
  });
  const page = await cc.newPage(); page.setDefaultTimeout(20000); await login(page, 'customer@example.test');
  await page.goto('/app/jobs/new');
  const map = page.getByRole('region', { name: 'Choose job location on map', exact: true });
  await expect(map.locator('.leaflet-control-attribution')).toContainText('OpenStreetMap');
  expect(await page.evaluate(() => window.locationRequests)).toBe(0);
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(0);
  await map.click({ position: { x: 120, y: 140 } });
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(1);
  await page.getByRole('button', { name: 'Remove location', exact: true }).click();
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(0);
  await map.focus(); await page.keyboard.press('Enter');
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(1);
  await page.getByRole('button', { name: 'Use my current location', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Use my current location', exact: true })).toBeEnabled();
  await expect(page.getByText('Precise job location added.', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => window.locationRequests)).toBe(1);
  await page.getByLabel('Service', { exact: true }).selectOption(service.id);
  await page.getByLabel('Request title').fill('Repair a bedroom electrical socket');
  await page.getByLabel('Describe the work').fill('Please check the bedroom socket and repair the loose wiring.');
  await page.getByLabel('General service area', { exact: true }).fill('Brikama');
  const posted = page.waitForResponse(r => r.url().endsWith('/job-requests') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Post request', exact: true }).click();
  const response = await posted; expect(response.ok()).toBe(true); const job = (await response.json()).data.jobRequest;
  expect(job.location).toEqual({ type: 'Point', coordinates: [-16.65, 13.27] });
  const opportunity = await request.get(api + '/job-requests/' + job.id + '/opportunity', { headers: wh });
  expect(opportunity.ok()).toBe(true); const opportunityData = (await opportunity.json()).data;
  expect(JSON.stringify(opportunityData)).not.toContain('coordinates');
  await page.goto('/app/jobs/' + job.id + '/edit');
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(1);
  await expect(page.getByLabel('Service', { exact: true })).toHaveValue(service.id);
  expect(await page.evaluate(() => window.locationRequests)).toBe(0);
  await page.screenshot({ path: 'test-results/job-map-1440.png', fullPage: true });
  await page.setViewportSize({ width: 375, height: 950 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/job-map-375.png', fullPage: true });
  const saved = page.waitForResponse(r => r.url().endsWith('/job-requests/' + job.id) && r.request().method() === 'PATCH');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  const edited = await saved; expect(edited.ok()).toBe(true);
  const editedJob = (await edited.json()).data.jobRequest;
  expect(editedJob.service).toBe(service.id); expect(editedJob.location).toEqual(job.location);

  await page.setViewportSize({ width: 1440, height: 950 });
  await page.goto('/app/proposals/new?worker=' + worker.user.id);
  await expect(map).toBeVisible();
  await page.getByRole('button', { name: 'Use my current location', exact: true }).click();
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(1);
  const marker = map.locator('.leaflet-marker-icon'); const box = await marker.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 10); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 55, box.y + 40, { steps: 12 }); await page.mouse.up();
  await page.getByLabel('Service', { exact: true }).selectOption(service.id);
  await page.getByLabel('What needs doing?').fill('Please inspect and repair the electrical socket at this pinned job site.');
  await page.getByLabel('Town / service area', { exact: true }).fill('Brikama');
  const date = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10);
  await page.getByLabel('Preferred start', { exact: true }).fill(date + 'T10:00');
  await page.getByLabel('Expected finish', { exact: true }).fill(date + 'T11:00');
  const proposalSent = page.waitForResponse(r => r.url().endsWith('/direct-proposals') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Send request', exact: true }).click();
  const proposalResponse = await proposalSent; expect(proposalResponse.ok()).toBe(true); const proposal = (await proposalResponse.json()).data.proposal;
  expect(proposal.location.type).toBe('Point');
  expect(proposal.location.coordinates).toHaveLength(2);
  expect(proposal.location.coordinates).not.toEqual([-16.65, 13.27]);
  expect(proposal.location.coordinates[0]).toBeLessThan(-16.6); expect(proposal.location.coordinates[1]).toBeGreaterThan(13.2);
  const hidden = (await (await request.get(api + '/direct-proposals/' + proposal.id, { headers: wh })).json()).data.proposal;
  expect(hidden).not.toHaveProperty('location');
  const quoted = await request.post(api + '/direct-proposals/' + proposal.id + '/quote', { headers: wh, data: { amountBututs: 50000, revision: 0 } });
  expect(quoted.ok()).toBe(true);
  const accepted = await request.post(api + '/direct-proposals/' + proposal.id + '/accept-quote', { headers: ch, data: { revision: 1 } });
  expect(accepted.ok()).toBe(true); const bookingId = (await accepted.json()).data.proposal.booking;
  const wc = await browser.newContext({ viewport: { width: 1440, height: 950 } }); const w = await wc.newPage();
  let workerTiles = 0; w.on('request', r => { if (r.url().startsWith('https://tile.openstreetmap.org/')) workerTiles++; });
  await login(w, 'professional@example.test'); await w.goto('/work/bookings/' + bookingId);
  await expect(w.getByText('Exact job location becomes available after the booking is confirmed.', { exact: true })).toBeVisible();
  await expect(w.getByRole('region', { name: 'Exact job location map' })).toHaveCount(0); expect(workerTiles).toBe(0);
  const unpaid = (await (await request.get(api + '/bookings/' + bookingId, { headers: wh })).json()).data.booking;
  expect(unpaid).not.toHaveProperty('location');
  expect((await request.post(api + '/payments/bookings/' + bookingId + '/checkout', { headers: ch, data: { outcome: 'SUCCESS', idempotencyKey: 'leaflet-map-paid' } })).ok()).toBe(true);
  await w.reload(); const paidMap = w.getByRole('region', { name: 'Exact job location map' });
  await expect(paidMap.locator('.leaflet-marker-icon')).toHaveCount(1);
  await expect(paidMap.locator('.leaflet-marker-draggable')).toHaveCount(0);
  await expect(w.getByRole('button', { name: 'Use my current location' })).toHaveCount(0);
  const paid = (await (await request.get(api + '/bookings/' + bookingId, { headers: wh })).json()).data.booking;
  expect(paid.location).toEqual(proposal.location);
  await w.screenshot({ path: 'test-results/paid-booking-map-1440.png', fullPage: true });
  await w.setViewportSize({ width: 375, height: 950 });
  expect(await w.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await w.screenshot({ path: 'test-results/paid-booking-map-375.png', fullPage: true });
  await cc.close(); await wc.close();
});

test('tile failure leaves pin selection and form completion available', async ({ page }) => {
  await page.route('https://tile.openstreetmap.org/**', route => route.abort());
  await login(page, 'customer@example.test'); await page.goto('/app/jobs/new');
  const map = page.getByRole('region', { name: 'Choose job location on map' });
  await expect(page.getByText(/Map tiles could not load/)).toBeVisible();
  await map.click({ position: { x: 140, y: 150 } });
  await expect(map.locator('.leaflet-marker-icon')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Post request', exact: true })).toBeEnabled();
});
